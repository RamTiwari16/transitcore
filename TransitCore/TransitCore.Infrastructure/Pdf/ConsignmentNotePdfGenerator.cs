using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using TransitCore.Application.Interfaces;
using TransitCore.Application.Models;

namespace TransitCore.Infrastructure.Pdf;

public class ConsignmentNotePdfGenerator : IConsignmentNotePdfGenerator
{
    static ConsignmentNotePdfGenerator()
    {
        // Same community-license note as InvoicePdfGenerator - see that
        // class for the revenue-threshold caveat to recheck before prod.
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public byte[] Generate(ConsignmentNoteDetailDto cn)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(2, Unit.Centimetre);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily(Fonts.Calibri));

                page.Header().Element(c => ComposeHeader(c, cn));
                page.Content().Element(c => ComposeContent(c, cn));
                page.Footer().AlignCenter().Text(x =>
                {
                    x.Span("Generated by TransitCore - page ");
                    x.CurrentPageNumber();
                    x.Span(" of ");
                    x.TotalPages();
                });
            });
        });

        return document.GeneratePdf();
    }

    private static void ComposeHeader(IContainer container, ConsignmentNoteDetailDto cn)
    {
        container.Row(row =>
        {
            row.RelativeItem().Column(column =>
            {
                column.Item().Text("TransitCore").FontSize(18).Bold();
                column.Item().Text("Fleet & Logistics Management").FontSize(9).FontColor(Colors.Grey.Darken1);
            });

            row.RelativeItem().Column(column =>
            {
                column.Item().AlignRight().Text("CONSIGNMENT NOTE").FontSize(16).Bold();
                column.Item().AlignRight().Text(cn.CnNumber).FontSize(11).FontColor(Colors.Grey.Darken2);
                column.Item().AlignRight().Text($"Status: {cn.StatusName}").FontSize(9);
            });
        });
    }

    private static void ComposeContent(IContainer container, ConsignmentNoteDetailDto cn)
    {
        container.PaddingTop(20).Column(column =>
        {
            column.Spacing(16);

            column.Item().Row(row =>
            {
                row.RelativeItem().Column(col =>
                {
                    col.Item().Text("Consignor").FontSize(9).FontColor(Colors.Grey.Darken1);
                    col.Item().Text(cn.ConsignorCustomerName ?? cn.ConsignorName ?? "-").FontSize(11).Bold();
                    if (!string.IsNullOrWhiteSpace(cn.ConsignorAddress))
                        col.Item().Text(cn.ConsignorAddress).FontSize(9);
                    if (!string.IsNullOrWhiteSpace(cn.ConsignorPhone))
                        col.Item().Text(cn.ConsignorPhone).FontSize(9);
                });

                row.RelativeItem().Column(col =>
                {
                    col.Item().Text("Consignee").FontSize(9).FontColor(Colors.Grey.Darken1);
                    col.Item().Text(cn.ConsigneeCustomerName ?? cn.ConsigneeName ?? "-").FontSize(11).Bold();
                    if (!string.IsNullOrWhiteSpace(cn.ConsigneeAddress))
                        col.Item().Text(cn.ConsigneeAddress).FontSize(9);
                    if (!string.IsNullOrWhiteSpace(cn.ConsigneePhone))
                        col.Item().Text(cn.ConsigneePhone).FontSize(9);
                });

                row.RelativeItem().Column(col =>
                {
                    col.Item().AlignRight().Text("Billing Party").FontSize(9).FontColor(Colors.Grey.Darken1);
                    col.Item().AlignRight().Text(cn.BillingPartyName).FontSize(11).Bold();
                    col.Item().AlignRight().Text($"Payment: {cn.FreightPaymentTypeName}").FontSize(9);
                });
            });

            column.Item().Row(row =>
            {
                row.RelativeItem().Text($"CN Date: {cn.CnDate:dd MMM yyyy}");
                row.RelativeItem().Text($"From: {cn.OriginCityName}");
                row.RelativeItem().Text($"To: {cn.DestinationCityName}");
                row.RelativeItem().Text($"Tracking No: {cn.TrackingNo ?? "-"}");
            });

            column.Item().Row(row =>
            {
                row.RelativeItem().Text($"Vehicle: {cn.VehicleRegistrationNo ?? "Not yet assigned"}");
                row.RelativeItem().Text($"Driver: {cn.DriverName ?? "Not yet assigned"}");
                row.RelativeItem().Text($"Packages: {(cn.Packages.HasValue ? cn.Packages.Value.ToString() : "-")}");
                row.RelativeItem().Text($"Declared Value: {(cn.DeclaredValue.HasValue ? cn.DeclaredValue.Value.ToString("N2") : "-")}");
            });

            column.Item().Row(row =>
            {
                row.RelativeItem().Text($"Actual Weight (kg): {(cn.ActualWeightKg.HasValue ? cn.ActualWeightKg.Value.ToString("N2") : "-")}");
                row.RelativeItem().Text($"Charged Weight (kg): {(cn.ChargedWeightKg.HasValue ? cn.ChargedWeightKg.Value.ToString("N2") : "-")}");
                row.RelativeItem().Text($"Freight Amount: {(cn.FreightAmount.HasValue ? cn.FreightAmount.Value.ToString("N2") : "-")}");
            });

            column.Item().Element(c => ComposeItemsTable(c, cn));

            if (!string.IsNullOrWhiteSpace(cn.Remarks))
            {
                column.Item().Column(col =>
                {
                    col.Item().Text("Remarks").FontSize(9).FontColor(Colors.Grey.Darken1);
                    col.Item().Text(cn.Remarks);
                });
            }

            if (cn.CancelReason is not null)
            {
                column.Item().Column(col =>
                {
                    col.Item().Text("Cancelled").FontSize(9).FontColor(Colors.Red.Darken1);
                    col.Item().Text($"{cn.CancelReason} ({cn.CancelledBy}, {cn.CancelledAt:dd MMM yyyy})").FontColor(Colors.Red.Darken1);
                });
            }
        });
    }

    private static void ComposeItemsTable(IContainer container, ConsignmentNoteDetailDto cn)
    {
        container.Table(table =>
        {
            table.ColumnsDefinition(columns =>
            {
                columns.RelativeColumn(4);
                columns.RelativeColumn();
                columns.RelativeColumn();
                columns.RelativeColumn();
            });

            table.Header(header =>
            {
                header.Cell().Element(HeaderCellStyle).Text("Description");
                header.Cell().Element(HeaderCellStyle).AlignRight().Text("Qty");
                header.Cell().Element(HeaderCellStyle).AlignRight().Text("Unit");
                header.Cell().Element(HeaderCellStyle).AlignRight().Text("Weight (kg)");
            });

            foreach (var item in cn.Items)
            {
                table.Cell().Element(BodyCellStyle).Text(item.Description);
                table.Cell().Element(BodyCellStyle).AlignRight().Text(item.Quantity.ToString("0.##"));
                table.Cell().Element(BodyCellStyle).AlignRight().Text(item.UnitOfMeasureCode);
                table.Cell().Element(BodyCellStyle).AlignRight().Text(item.WeightKg.HasValue ? item.WeightKg.Value.ToString("N2") : "-");
            }

            static IContainer HeaderCellStyle(IContainer c) =>
                c.DefaultTextStyle(x => x.SemiBold()).PaddingBottom(6).BorderBottom(1).BorderColor(Colors.Grey.Darken1);

            static IContainer BodyCellStyle(IContainer c) =>
                c.PaddingVertical(6).BorderBottom(1).BorderColor(Colors.Grey.Lighten2);
        });
    }
}

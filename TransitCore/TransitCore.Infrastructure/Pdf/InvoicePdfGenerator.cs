using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using TransitCore.Application.Interfaces;
using TransitCore.Application.Models;

namespace TransitCore.Infrastructure.Pdf;

public class InvoicePdfGenerator : IInvoicePdfGenerator
{
    static InvoicePdfGenerator()
    {
        // Free for small companies/individuals (under $1M USD annual gross
        // revenue) and open-source/non-profit use - see
        // https://www.questpdf.com/license/overview.html. Confirm this
        // still applies before shipping to production if that changes.
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public byte[] Generate(InvoiceDetailDto invoice)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(2, Unit.Centimetre);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily(Fonts.Calibri));

                page.Header().Element(c => ComposeHeader(c, invoice));
                page.Content().Element(c => ComposeContent(c, invoice));
                page.Footer().AlignCenter().Text(x =>
                {
                    x.Span("Generated by TransitCore - page ");
                    x.CurrentPageNumber();
                    x.Span(" of ");
                    x.TotalPages();
                });
            });
        });

        return document.GeneratePdf();
    }

    private static void ComposeHeader(IContainer container, InvoiceDetailDto invoice)
    {
        container.Row(row =>
        {
            row.RelativeItem().Column(column =>
            {
                column.Item().Text("TransitCore").FontSize(18).Bold();
                column.Item().Text("Fleet & Logistics Management").FontSize(9).FontColor(Colors.Grey.Darken1);
            });

            row.RelativeItem().Column(column =>
            {
                column.Item().AlignRight().Text("INVOICE").FontSize(18).Bold();
                column.Item().AlignRight().Text(invoice.InvoiceNo).FontSize(11).FontColor(Colors.Grey.Darken2);
            });
        });
    }

    private static void ComposeContent(IContainer container, InvoiceDetailDto invoice)
    {
        container.PaddingTop(20).Column(column =>
        {
            column.Spacing(16);

            column.Item().Row(row =>
            {
                row.RelativeItem().Column(col =>
                {
                    col.Item().Text("Bill To").FontSize(9).FontColor(Colors.Grey.Darken1);
                    col.Item().Text(invoice.CustomerName).FontSize(12).Bold();
                });

                row.RelativeItem().Column(col =>
                {
                    col.Item().AlignRight().Text($"Invoice Date: {invoice.InvoiceDate:dd MMM yyyy}");
                    col.Item().AlignRight().Text($"Due Date: {invoice.DueDate:dd MMM yyyy}");
                    col.Item().AlignRight().Text($"Status: {invoice.StatusName}").Bold();
                });
            });

            column.Item().Element(c => ComposeLinesTable(c, invoice));

            column.Item().AlignRight().Column(col =>
            {
                col.Item().Row(r =>
                {
                    r.RelativeItem().AlignRight().Text("Subtotal");
                    r.ConstantItem(100).AlignRight().Text(invoice.Subtotal.ToString("N2"));
                });
                if (invoice.DiscountAmount > 0)
                {
                    col.Item().Row(r =>
                    {
                        r.RelativeItem().AlignRight().Text("Discount");
                        r.ConstantItem(100).AlignRight().Text($"-{invoice.DiscountAmount:N2}");
                    });
                }
                col.Item().Row(r =>
                {
                    r.RelativeItem().AlignRight().Text("Tax");
                    r.ConstantItem(100).AlignRight().Text(invoice.TaxAmount.ToString("N2"));
                });
                col.Item().PaddingTop(4).BorderTop(1).BorderColor(Colors.Grey.Darken1).Row(r =>
                {
                    r.RelativeItem().AlignRight().Text("Total").Bold();
                    r.ConstantItem(100).AlignRight().Text(invoice.TotalAmount.ToString("N2")).Bold();
                });
                if (invoice.PaidAmount > 0)
                {
                    col.Item().Row(r =>
                    {
                        r.RelativeItem().AlignRight().Text("Paid");
                        r.ConstantItem(100).AlignRight().Text(invoice.PaidAmount.ToString("N2"));
                    });
                }
                if (invoice.DeductionAmount > 0)
                {
                    col.Item().Row(r =>
                    {
                        r.RelativeItem().AlignRight().Text("Deduction");
                        r.ConstantItem(100).AlignRight().Text($"-{invoice.DeductionAmount:N2}");
                    });
                }
                if (invoice.PaidAmount > 0 || invoice.DeductionAmount > 0)
                {
                    col.Item().Row(r =>
                    {
                        r.RelativeItem().AlignRight().Text("Balance Due").Bold();
                        r.ConstantItem(100).AlignRight().Text((invoice.TotalAmount - invoice.PaidAmount - invoice.DeductionAmount).ToString("N2")).Bold();
                    });
                }
            });
        });
    }

    private static void ComposeLinesTable(IContainer container, InvoiceDetailDto invoice)
    {
        container.Table(table =>
        {
            table.ColumnsDefinition(columns =>
            {
                columns.RelativeColumn(4);
                columns.RelativeColumn();
                columns.RelativeColumn();
                columns.RelativeColumn();
            });

            table.Header(header =>
            {
                header.Cell().Element(HeaderCellStyle).Text("Description");
                header.Cell().Element(HeaderCellStyle).AlignRight().Text("Qty");
                header.Cell().Element(HeaderCellStyle).AlignRight().Text("Unit Price");
                header.Cell().Element(HeaderCellStyle).AlignRight().Text("Line Total");
            });

            foreach (var line in invoice.Lines)
            {
                table.Cell().Element(BodyCellStyle).Text(line.Description);
                table.Cell().Element(BodyCellStyle).AlignRight().Text(line.Quantity.ToString("0.##"));
                table.Cell().Element(BodyCellStyle).AlignRight().Text(line.UnitPrice.ToString("N2"));
                table.Cell().Element(BodyCellStyle).AlignRight().Text(line.LineTotal.ToString("N2"));
            }

            static IContainer HeaderCellStyle(IContainer c) =>
                c.DefaultTextStyle(x => x.SemiBold()).PaddingBottom(6).BorderBottom(1).BorderColor(Colors.Grey.Darken1);

            static IContainer BodyCellStyle(IContainer c) =>
                c.PaddingVertical(6).BorderBottom(1).BorderColor(Colors.Grey.Lighten2);
        });
    }
}
